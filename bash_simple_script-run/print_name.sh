#!/bin/bash
# This line above is the shebang - tells Linux to run this with bash

echo "Hello Everyone, My name is Power Vijaya"
# echo just prints text to the screen

name="Vijaya Power"
# This creates a VARIABLE called "name" and stores the text "Vijaya" in it
# No spaces around the = sign - this is a strict bash rule

echo "Hii $name, Welcome to Bash scripting."
# $name means "grab whatever is stored in the variable called name"
# Output: Hi Vijaya, welcome to scripting